def expr(p,newton=False):
 den=reduce(lcm,(v.denominator for v in p.values()),1)
 terms=[]
 for (a,b),v in sorted(p.items()):
  assert v>=0
  c=str(int(v*den))
  if newton:
   if a:c+=f' * choosePolyM0D3 x {a}'
   if b:c+=f' * choosePolyM0D3 y {b}'
  else:
   if a:c+=' * x'+(f'^{a}' if a!=1 else '')
   if b:c+=' * y'+(f'^{b}' if b!=1 else '')
  terms.append(c)
 return '(\n   '+' +\n   '.join(terms)+'\n  ) / '+str(den)
